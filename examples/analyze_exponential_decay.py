"""Synthetic example with known parameters for nonlinear exponential fitting."""

from __future__ import annotations

from pathlib import Path

import numpy as np

from physlab_qa.nonlinear import nonlinear_fit
from physlab_qa.report import write_nonlinear_fit_report

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "build" / "exponential-decay-report.md"


def exponential_decay(x, amplitude, decay_rate, offset):
    return amplitude * np.exp(-decay_rate * x) + offset


def main() -> int:
    # Deterministic synthetic observations: true parameters are A=2.5, k=0.8, C=0.3.
    x = np.linspace(0.0, 5.0, 31)
    y = exponential_decay(x, 2.5, 0.8, 0.3) + 0.015 * np.sin(2.7 * x)
    result = nonlinear_fit(
        x,
        y,
        model=exponential_decay,
        p0=[2.0, 0.5, 0.1],
        parameter_names=("amplitude", "decay_rate", "offset"),
        model_name="exponential-decay",
    )
    write_nonlinear_fit_report(
        result,
        x_name="time_s",
        y_name="signal",
        source_path="deterministic synthetic data generated by this example",
        model_equation="y = A exp(−k t) + C",
        output_path=OUTPUT,
        title="Exponential decay: nonlinear fitting demonstration",
    )
    print("Synthetic demonstration only; do not cite as experimental evidence.")
    print(f"Converged: {result.converged} (status {result.optimizer_status})")
    for name, value, stderr in zip(
        result.parameter_names, result.parameters, result.parameter_stderr
    ):
        print(f"{name}: {value:.6g} +/- {stderr:.3g}")
    print(f"R²: {result.r_squared:.8g}")
    print(f"Markdown report: {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
